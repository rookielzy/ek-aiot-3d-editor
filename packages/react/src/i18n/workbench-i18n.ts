export type WorkbenchMessageKey = keyof typeof EN_WORKBENCH_MESSAGES;
type BuiltinWorkbenchMessageDescriptor = {
  [Key in WorkbenchMessageKey]: {
    key: Key;
    fallback: (typeof EN_WORKBENCH_MESSAGES)[Key];
    values?: WorkbenchMessageValues;
  };
}[WorkbenchMessageKey];

export interface WorkbenchMessageDescriptor {
  key: MessageKey;
  fallback: string;
  values?: WorkbenchMessageValues;
}

export type WorkbenchMessageInput = WorkbenchMessageKey | BuiltinWorkbenchMessageDescriptor | WorkbenchMessageDescriptor | MessageDescriptor;

export type WorkbenchTranslate = (
  descriptor: WorkbenchMessageDescriptor | MessageDescriptor,
  locale: WorkbenchLocale
) => string | undefined;

