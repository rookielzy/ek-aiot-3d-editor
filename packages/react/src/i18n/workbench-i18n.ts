export const WORKBENCH_DICTIONARIES: Readonly<Record<WorkbenchLocale, WorkbenchDictionary>> = Object.freeze({
  en: Object.freeze(EN_WORKBENCH_MESSAGES),
  "zh-CN": Object.freeze(ZH_CN_WORKBENCH_MESSAGES)
});

export function resolveWorkbenchMessage(
  locale: WorkbenchLocale,
  message: WorkbenchMessageInput,
  values?: WorkbenchMessageValues,
  translate?: WorkbenchTranslate
): string {
  const descriptor = normalizeWorkbenchMessage(message, values);
  const override = resolveHostTranslation(descriptor, locale, translate);
  if (override !== undefined) {
    return interpolateMessage(override, descriptor.values);
  }

  const key = descriptor.key as WorkbenchMessageKey;
  const template = WORKBENCH_DICTIONARIES[locale][key] ??
    WORKBENCH_DICTIONARIES[DEFAULT_WORKBENCH_LOCALE][key] ??
    descriptor.fallback;
  return interpolateMessage(template, descriptor.values);
}

function resolveHostTranslation(
  descriptor: WorkbenchMessageDescriptor,
  locale: WorkbenchLocale,
  translate: WorkbenchTranslate | undefined
): string | undefined {
  try {
    const override = translate?.(descriptor, locale);
    return typeof override === "string" ? override : undefined;
  } catch {
    return undefined;
  }
}

export function normalizeWorkbenchLocale(locale: WorkbenchLocale | undefined): WorkbenchLocale {
  return locale && WORKBENCH_LOCALES.includes(locale) ? locale : DEFAULT_WORKBENCH_LOCALE;
}

export function isWorkbenchLocale(value: unknown): value is WorkbenchLocale {
  return WORKBENCH_LOCALES.includes(value as WorkbenchLocale);
}

export function getWorkbenchLocaleLabel(locale: WorkbenchLocale): string {
  return WORKBENCH_LOCALE_LABELS[locale] ?? locale;
}

function normalizeWorkbenchMessage(
  message: WorkbenchMessageInput,
  values?: WorkbenchMessageValues
): WorkbenchMessageDescriptor {
  if (typeof message === "string") {
    return {
      key: message,
      fallback: message,
      ...(values ? { values } : {})
    };
  }

  return {
    key: message.key,
    fallback: message.fallback,
    values: {
      ...(message.values ?? {}),
      ...(values ?? {})
    }
  };
}

function interpolateMessage(template: string, values: WorkbenchMessageValues | undefined): string {
  if (!values) {
    return template;
  }
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, key) => {
    const value = values[key];
    if (value === undefined || value === null) {
      return "";
    }
    if (typeof value === "object") {
      return match;
    }
    return String(value);
  });
}
