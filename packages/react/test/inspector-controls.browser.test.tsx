import React from "react";
import { createRoot } from "react-dom/client";
import { page, userEvent } from "vitest/browser";
import { expect, it } from "vitest";
import { createEditor } from "@ek-aiot/3d-editor-core";
import { InspectorPanel } from "../src/components/InspectorPanel";
import { selectInspectorOption } from "./support/inspector-browser";

it("keeps keyboard focus, cancels target-switch drafts and isolates themed portals in a narrow Inspector", async () => {
  const editor = createEditor();
  for (const id of ["a", "b"]) editor.dispatch({ type: "import-glb", objectId: id, asset: { id: `asset-${id}` } });
  editor.dispatch({ type: "select-object", objectId: "a" });
  editor.dispatch({ type: "register-asset", asset: { id: "studio", kind: "hdr", label: "Studio HDR" } });
  editor.dispatch({ type: "register-asset", asset: { id: "outside", kind: "hdr", label: "Outside HDR" } });
  const host = document.createElement("div");
  host.style.cssText = "width:280px;height:650px;position:fixed;right:8px;top:8px;--ek-workbench-surface-raised:#192536;--ek-workbench-surface:#111827;--ek-workbench-text:#e4e9f0;--ek-workbench-border:#475569;--ek-workbench-accent:#60a5fa;--ek-workbench-accent-soft:#243c60";
  const outside = document.createElement("button");
  outside.textContent = "Host button";
  document.body.append(host, outside);
  const outsideStyle = getComputedStyle(outside);
  const originalStyle = { background: outsideStyle.backgroundColor, padding: outsideStyle.padding, border: outsideStyle.borderWidth };
  const target = document.createElement("button");
  target.textContent = "Select B";
  target.style.cssText = "position:fixed;left:4px;top:60px;width:44px;z-index:1100";
  target.dataset.ekDiscardDraft = "";
  target.onclick = () => { editor.dispatch({ type: "select-object", objectId: "b" }); };
  document.body.append(target);
  const root = createRoot(host);
  try {
    root.render(<InspectorPanel editor={editor} />);
    await expect.poll(() => host.querySelector('[aria-label="Position X"]')).toBeTruthy();
    const input = () => host.querySelector<HTMLInputElement>('[aria-label="Position X"]')!;
    const before = editor.getHistoryState().undoCount;
    await userEvent.fill(input(), "2");
    await userEvent.keyboard("{Enter}");
    expect(document.activeElement).toBe(input());
    await userEvent.keyboard("{Tab}");
    expect(editor.getHistoryState().undoCount).toBe(before + 1);
    await userEvent.fill(input(), "9");
    await userEvent.click(target);
    expect(editor.getSnapshot().objects.a.transform.position[0]).toBe(2);
    await expect.poll(() => input().value).toBe("0");
    await userEvent.fill(input(), "");
    await userEvent.keyboard("{Enter}");
    expect(input().getAttribute("aria-invalid")).toBe("true");
    await userEvent.keyboard("{Escape}");
    expect(input().value).toBe("0");
    expect(input().getAttribute("aria-invalid")).toBeNull();

    const transform = page.getByRole("tab", { name: "Transform", exact: true });
    const material = page.getByRole("tab", { name: "Material", exact: true });
    const snapshot = editor.getSnapshot();
    await userEvent.click(transform);
    await userEvent.keyboard("{ArrowRight}");
    await expect.element(material).toHaveAttribute("aria-selected", "true");
    expect(document.activeElement).toBe(material.element());
    expect(input().checkVisibility()).toBe(false);
    expect(editor.getSnapshot()).toBe(snapshot);
    const side = host.querySelector<HTMLButtonElement>('[aria-label="Side"]')!;
    side.focus();
    await userEvent.keyboard("{ArrowDown}");
    await expect.poll(() => document.querySelector(".ek-ui-select-content")).toBeTruthy();
    const popup = document.querySelector<HTMLElement>(".ek-ui-select-content")!;
    expect(host.contains(popup)).toBe(false);
    expect(getComputedStyle(popup).backgroundColor).toBe("rgb(25, 37, 54)");
    const bounds = popup.getBoundingClientRect();
    expect(bounds.right).toBeLessThanOrEqual(window.innerWidth);
    expect(bounds.bottom).toBeLessThanOrEqual(window.innerHeight);
    await userEvent.keyboard("{Escape}");
    await expect.poll(() => document.activeElement).toBe(side);
    await selectInspectorOption(side, "double");
    await expect.poll(() => document.activeElement).toBe(side);
    await userEvent.click(host.querySelector('[role="tab"][id$="-tab-environment"]')!);
    const asset = host.querySelector<HTMLButtonElement>('[aria-label="Lighting asset"]')!;
    await userEvent.click(asset);
    const search = document.querySelector<HTMLInputElement>("[cmdk-input]")!;
    await userEvent.fill(search, "Outside");
    await expect.poll(() => document.querySelectorAll('[cmdk-item]').length).toBe(1);
    await userEvent.keyboard("{ArrowDown}{Enter}");
    await expect.poll(() => editor.getSnapshot().environment.lighting.source).toEqual({ kind: "hdr", assetId: "outside" });
    await expect.poll(() => document.activeElement).toBe(asset);
    await userEvent.click(asset);
    await userEvent.fill(document.querySelector<HTMLInputElement>("[cmdk-input]")!, "missing-search");
    await expect.poll(() => document.querySelector("[cmdk-empty]")?.textContent).toBe("No matching assets.");
    await userEvent.keyboard("{Escape}");
    expect(editor.getSnapshot().environment.lighting.source).toEqual({ kind: "hdr", assetId: "outside" });
    await expect.poll(() => document.activeElement).toBe(asset);
    await userEvent.click(page.getByRole("tab", { name: "Properties", exact: true }));
    await expect.element(material).toHaveAttribute("aria-selected", "true");
    expect(side.checkVisibility()).toBe(true);
    expect({ background: outsideStyle.backgroundColor, padding: outsideStyle.padding, border: outsideStyle.borderWidth }).toEqual(originalStyle);
  } finally {
    root.unmount();
    editor.dispose();
    host.remove(); outside.remove(); target.remove();
  }
}, 30000);
